		<p align="justify"> <b>Moise Mupata, Président de la Ligue des Jeunes</b>, a mis en lumière le rôle crucial de la jeunesse, affirmant que "la force de notre parti repose sur deux piliers fondamentaux: l'engagement des femmes et la mobilisation de la Ligue des Jeunes". Il a rappelé que la jeunesse devait être au cœur des actions du parti, à l'image de figures emblématiques comme Lumumba et Nelson Mandela, et qu'elle avait la responsabilité de fournir des informations précieuses et de détecter les problèmes.</p>

	  <p align="justify"> <b>Jully MAMBULU, Secrétaire National en charge des Questions Politiques</b>, a défini le militantisme comme une action personnelle ou collective visant à agir ou à lutter pour un sujet donné, insistant sur la détermination et l'engagement à persuader. Il a souligné que le militant devait être exemplaire, agissant comme un ambassadeur des valeurs et idéaux de l'ACP, et portant les symboles du parti.</p>
		
		
