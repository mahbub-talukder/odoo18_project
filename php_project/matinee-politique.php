		<p align="justify"> <b>Le Secrétaire Général, Charles MBUTA MUNTU</b>,  a appelé à un engagement total, invitant chaque membre à se considérer comme une partie intégrante du projet ACP, se demandant : « Que sème-je ? ». Il a insisté sur une déclaration d'engagement personnel (« Moi et ma maison, nous servirons l'ACP »), une communication positive et un soutien concret, concrétisé par une collecte spontanée qui a recueilli un élan de générosité de la salle. Pour Muntu, la loyauté, comparée à l'attachement à un être cher, est la clé de voûte de la durabilité du parti, rappelant l'exemple de loyauté incarné par le PALU sous Kizenga. L'avenir de l'ACP, a-t-il conclu, repose sur cet engagement indéfectible.  </p>
	  
	  
		<p align="justify"> <b>Pius KANDOLO, le Secrétaire Général Adjoint (SGA)</b>, a ensuite entraîné l'assemblée dans une exploration de "la belle ACP", l'hymne de l'alliance, renforçant le sentiment d'appartenance parmi les cadres. <br>
