		<p class="ubuntu-font" align="justify"> Suite aux récentes allégations de l’Observatoire de la Dépense Publique (ODEP) concernant le financement et la gestion du projet de construction du marché central Zando, l’ancien gouverneur de Kinshasa, Gentiny Ngobila Mbaka, tient à apporter les précisions suivantes : </p>
	  
	  
		<p align="justify"> <b>Point 1</b> : Absence de fonds publics Contrairement aux allégations de l’ODEP, la ville de Kinshasa n’a déboursé aucun fonds public pour le projet Zando. Le financement a été entièrement assuré par la Sofibank, sollicitée par la société SOGEMA, adjudicataire du marché, conformément aux procédures de passation des marchés en vigueur.

 </p>
 
 <p align="justify">
     <b>Point 2 :</b> Respect des procédures et transparence financière Le projet Zando a respecté scrupuleusement toutes les étapes de la procédure de passation des marchés. Un avis de non-objection a été obtenu. Afin de garantir la transparence, un fonds d'investissement a été créé, ainsi qu'un compte séquestre actuellement approvisionné à hauteur de 35 millions de dollars sur un projet total de 54 millions. Ce compte séquestre garantit la traçabilité des fonds et le respect des engagements contractuels.
 </p>
		
		
