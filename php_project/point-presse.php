		<p align="justify"> <b>Point 3 :</b> Partenariat public-privé et partage des recettes Il s'agit d'un partenariat public-privé clair et transparent. SOGEMA assurera la gestion du marché pendant 4 ans et demi. Durant cette période, la ville de Kinshasa percevra 20% des recettes. Après cette période, ce pourcentage passera à 80%, garantissant un retour sur investissement significatif pour la ville.</p>
		
		<p align="justify"> <b>Point 4</b> : Réponse aux accusations de l’ODEP Nous réfutons catégoriquement les accusations de « gouvernance léonine » et d’opacité totale formulées par l’ODEP. L’allégation d’un versement de 20% des recettes à SOGEMA pendant 25 ans est totalement infondée. Nous proposons à l’ODEP, ainsi qu’à tous les médias, de prendre connaissance du contrat pour une analyse objective et transparente de son contenu. Cette transparence vise à dissiper tous les doutes et à rétablir la vérité sur la gestion du projet Zando.</p>
	  
	  
	  <p align="justify"> <b>Conclusion</b> Le projet Zando est un projet majeur pour la ville de Kinshasa. Son financement et sa gestion ont été menés avec la plus grande rigueur et transparence. Nous restons ouverts à toute demande d’information complémentaire et réaffirmons notre engagement à la bonne gouvernance et au développement de notre ville. </p>
		
